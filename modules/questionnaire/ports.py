"""Ports for immutable questionnaires and their staged generation inputs."""

from __future__ import annotations

from typing import Protocol


class QuestionnaireStore(Protocol):
    async def insert(self, snapshot: dict) -> bool: ...
    async def save(self, snapshot: dict, *, expected_revision: str) -> bool: ...
    async def get_by_id(self, user_id: str, questionnaire_id: str) -> dict | None: ...
    async def get_current(self, user_id: str, session_id: str) -> dict | None: ...
    async def get_submitted(self, user_id: str, questionnaire_id: str) -> dict | None: ...
    async def list_recoverable(self, *, now: float, limit: int = 100) -> list[dict]: ...
    async def list_pending_ingestion(self, *, limit: int = 100) -> list[dict]: ...
    async def mark_ingestion_queued(self, user_id: str, questionnaire_id: str, job_id: str) -> bool: ...
    async def mark_ingestion_source_managed(
        self, user_id: str, questionnaire_id: str, *, source_revision: int
    ) -> bool: ...
    async def get_for_factor_assessment(self, user_id: str, questionnaire_id: str) -> dict | None: ...
    async def list_pending_factor_assessments(self, *, limit: int = 100) -> list[dict]: ...
    async def mark_factor_assessment_queued(
        self,
        user_id: str,
        questionnaire_id: str,
        assessment_id: str,
    ) -> bool: ...


class QuestionnaireFactorEvaluator(Protocol):
    async def evaluate(self, snapshot: dict, *, checkpoint=None) -> dict: ...


class QuestionnaireFactorTaskStore(Protocol):
    async def admit(self, specification: dict, *, terminal_error: str | None = None) -> dict: ...
    async def get(self, user_id: str, questionnaire_id: str, assessment_id: str) -> dict | None: ...
    async def claim(self, owner: str, *, lease_seconds: float, max_attempts: int) -> dict | None: ...
    async def renew(self, job: dict, *, lease_seconds: float) -> bool: ...
    async def bind_execution(self, job: dict, *, expected_manifest: dict | None) -> bool: ...
    async def save_checkpoint(self, job: dict, checkpoint: dict) -> bool: ...
    async def complete(self, job: dict, result: dict) -> bool: ...
    async def fail(
        self,
        job: dict,
        *,
        error_code: str,
        retryable: bool,
        max_attempts: int,
        delay_seconds: float,
    ) -> bool: ...
    async def recover_exhausted(self, *, max_attempts: int, limit: int = 100) -> int: ...


class QuestionnaireGenerator(Protocol):
    async def generate(self, *, user_id: str, questionnaire_id: str, file_list: list[dict]) -> dict: ...
    async def ready_artifacts(self, snapshot: dict, expires_at: float) -> None: ...
    async def pin_artifacts(self, snapshot: dict) -> None: ...
    async def expire_artifacts(self, snapshot: dict) -> None: ...


class QuestionnaireOwnerRepository(Protocol):
    async def get(self, user_id: str, session_id: str) -> dict | None: ...
    async def save_questionnaire_owner(
        self,
        user_id: str,
        session_id: str,
        session: dict,
        *,
        expected: dict | None,
    ) -> bool: ...
