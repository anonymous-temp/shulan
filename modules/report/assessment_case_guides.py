    '认知校准（recognitions）：受检者的自述或体检结论的文字里，有与数据不符或容易误解的地方时列出 2–4 条；没有就留空。',
    '只做判断和归类，不写正文。除 note、because 外的文字字段都是短语。不要自己计算资料里没有的综合指数。',
